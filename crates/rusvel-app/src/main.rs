/// Object store bucket for [`EventTrigger`] definitions (CRUD can be added via API later).
const EVENT_TRIGGERS_STORE: &str = "event_triggers";

async fn load_event_triggers_from_store(
    tm: &TriggerManager,
    storage: &Arc<dyn StoragePort>,
) -> Result<()> {
    let rows = storage
        .objects()
        .list(EVENT_TRIGGERS_STORE, ObjectFilter::default())
        .await
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    let mut n = 0usize;
    for v in rows {
        if let Ok(t) = serde_json::from_value::<EventTrigger>(v) {
            tm.register_trigger(t);
            n += 1;
        }
    }
    if n > 0 {
        tracing::info!("Loaded {n} event trigger(s) from object store");
    } else {
        tracing::debug!("No event triggers in object store ({EVENT_TRIGGERS_STORE})");
    }
    Ok(())
}

const SESSION_JOB_LOG_WINDOW: &str = "session-job-log";

async fn ensure_session_job_log_pane(
    term: &Arc<dyn rusvel_core::ports::TerminalPort>,
    session_id: &SessionId,
) -> Option<rusvel_core::id::PaneId> {
    use rusvel_core::terminal::{PaneSize, PaneSource, WindowSource};
    use std::path::PathBuf;

    let Ok(panes) = term.list_panes_for_session(session_id).await else {
        return None;
    };
    if let Some(p) = panes
        .iter()
        .find(|p| matches!(&p.source, PaneSource::SessionLog))
    {
        return Some(p.id);
    }

    let window_id = match term
        .create_window(session_id, SESSION_JOB_LOG_WINDOW, WindowSource::Manual)
        .await
    {
        Ok(id) => id,
        Err(e) => {
            tracing::debug!(error = %e, "ensure_session_job_log_pane: create_window");
            return None;
        }
    };
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("/"));
    match term
        .create_pane(
            &window_id,
            "sleep 86400",
            &cwd,
            PaneSize { rows: 24, cols: 80 },
            PaneSource::SessionLog,
            None,
        )
        .await
    {
        Ok(id) => Some(id),
        Err(e) => {
            tracing::debug!(error = %e, "ensure_session_job_log_pane: create_pane");
            None
        }
    }
}

async fn pane_scrollback_snippet_for_approval(
    terminal: &Arc<dyn rusvel_core::ports::TerminalPort>,
    pane_id: &rusvel_core::id::PaneId,
) -> String {
    const MAX_BYTES: usize = 8192;
    const MAX_LINES: usize = 28;
    const MAX_CHARS: usize = 4000;

    let Ok(buf) = terminal.pane_scrollback(pane_id).await else {
        return String::new();
    };
    if buf.is_empty() {
        return String::new();
    }
    let start = buf.len().saturating_sub(MAX_BYTES);
    let chunk = &buf[start..];
    let s = String::from_utf8_lossy(chunk);
    let lines: Vec<&str> = s.lines().collect();
    let n = lines.len().min(MAX_LINES);
    let lo = lines.len().saturating_sub(n);
    let mut out = lines[lo..].join("\n");
    if out.chars().count() > MAX_CHARS {
        out = out
            .chars()
            .rev()
            .take(MAX_CHARS)
            .collect::<String>()
            .chars()
            .rev()
            .collect();
        out.insert(0, '…');
    }
    out
}

async fn stamp_job_approval_terminal_links(
    storage: &Arc<dyn StoragePort>,
    terminal: &Arc<dyn rusvel_core::ports::TerminalPort>,
    job_id: &rusvel_core::id::JobId,
    session_id: &SessionId,
    dept_id: &str,
) {
    use rusvel_core::terminal::PaneSource;

    let Ok(panes) = terminal.list_panes_for_session(session_id).await else {
        return;
    };
    let Some(p) = panes
        .iter()
        .find(|p| matches!(&p.source, PaneSource::Department(d) if d.as_str() == dept_id))
    else {
        return;
    };
    let Ok(Some(mut job)) = storage.jobs().get(job_id).await else {
        return;
    };
    if job.metadata.as_object().is_none() {
        job.metadata = serde_json::json!({});
    }
    let Some(m) = job.metadata.as_object_mut() else {
        return;
    };
    m.insert(
        "terminal_pane_id".into(),
        serde_json::json!(p.id.to_string()),
    );
    m.insert(
        "terminal_window_id".into(),
        serde_json::json!(p.window_id.to_string()),
    );
    m.insert("terminal_dept_id".into(), serde_json::json!(dept_id));

    let snippet = pane_scrollback_snippet_for_approval(terminal, &p.id).await;
    if !snippet.trim().is_empty() {
        m.insert(
            "terminal_context_snippet".into(),
            serde_json::json!(snippet),
        );
    }
    let _ = storage.jobs().update(&job).await;
}

